// QA-029-01: a fresh Idempotency-Key that works on every page. Browsers expose `crypto.randomUUID` only in secure contexts (HTTPS
// or localhost), so a plain-HTTP deployment reached by IP or hostname has none; `crypto.getRandomValues` exists in every context
// and gives the same random version-4 UUID.
export function newIdempotencyKey(): string {
  if (typeof crypto.randomUUID === "function") return crypto.randomUUID();
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  bytes[6] = (bytes[6] & 0x0f) | 0x40; // version 4
  bytes[8] = (bytes[8] & 0x3f) | 0x80; // RFC 4122 variant
  const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
